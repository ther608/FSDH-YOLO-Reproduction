class ConvTranspose(nn.Module):
    """Convolution transpose module with optional batch normalization and activation.

    Attributes:
        conv_transpose (nn.ConvTranspose2d): Transposed convolution layer.
        bn (nn.BatchNorm2d | nn.Identity): Batch normalization layer.
        act (nn.Module): Activation function layer.
        default_act (nn.Module): Default activation function (SiLU).
    """

    default_act = nn.SiLU()  # default activation

    def __init__(self, c1, c2, k=2, s=2, p=0, bn=True, act=True):
        """Initialize ConvTranspose layer with given parameters.

        Args:
            c1 (int): Number of input channels.
            c2 (int): Number of output channels.
            k (int): Kernel size.
            s (int): Stride.
            p (int): Padding.
            bn (bool): Use batch normalization.
            act (bool | nn.Module): Activation function.
        """
        super().__init__()
        self.conv_transpose = nn.ConvTranspose2d(c1, c2, k, s, p, bias=not bn)
        self.bn = nn.BatchNorm2d(c2) if bn else nn.Identity()
        self.act = self.default_act if act is True else act if isinstance(act, nn.Module) else nn.Identity()

    def forward(self, x):
        """Apply transposed convolution, batch normalization and activation to input.

        Args:
            x (torch.Tensor): Input tensor.

        Returns:
            (torch.Tensor): Output tensor.
        """
        return self.act(self.bn(self.conv_transpose(x)))

    def forward_fuse(self, x):
        """Apply activation and convolution transpose operation to input.

        Args:
            x (torch.Tensor): Input tensor.

        Returns:
            (torch.Tensor): Output tensor.
        """
        return self.act(self.conv_transpose(x))


class Focus(nn.Module):
    """Focus module for concentrating feature information.

    Slices input tensor into 4 parts and concatenates them in the channel dimension.

    Attributes:
        conv (Conv): Convolution layer.
    """

    def __init__(self, c1, c2, k=1, s=1, p=None, g=1, act=True):
        """Initialize Focus module with given parameters.

        Args:
            c1 (int): Number of input channels.
            c2 (int): Number of output channels.
            k (int): Kernel size.
            s (int): Stride.
            p (int, optional): Padding.
            g (int): Groups.
            act (bool | nn.Module): Activation function.
        """
        super().__init__()
        self.conv = Conv(c1 * 4, c2, k, s, p, g, act=act)
        # self.contract = Contract(gain=2)

    def forward(self, x):
        """Apply Focus operation and convolution to input tensor.

        Input shape is (B, C, W, H) and output shape is (B, 4C, W/2, H/2).

        Args:
            x (torch.Tensor): Input tensor.

        Returns:
            (torch.Tensor): Output tensor.
        """
        return self.conv(torch.cat((x[..., ::2, ::2], x[..., 1::2, ::2], x[..., ::2, 1::2], x[..., 1::2, 1::2]), 1))
        # return self.conv(self.contract(x))


class GhostConv(nn.Module):
    """Ghost Convolution module.

    Generates more features with fewer parameters by using cheap operations.

    Attributes:
        cv1 (Conv): Primary convolution.
        cv2 (Conv): Cheap operation convolution.

    References:
        https://github.com/huawei-noah/Efficient-AI-Backbones
    """

    def __init__(self, c1, c2, k=1, s=1, g=1, act=True):
        """Initialize Ghost Convolution module with given parameters.

        Args:
            c1 (int): Number of input channels.
            c2 (int): Number of output channels.
            k (int): Kernel size.
            s (int): Stride.
            g (int): Groups.
            act (bool | nn.Module): Activation function.
        """
        super().__init__()
        c_ = c2 // 2  # hidden channels
        self.cv1 = Conv(c1, c_, k, s, None, g, act=act)
        self.cv2 = Conv(c_, c_, 5, 1, None, c_, act=act)

    def forward(self, x):
        """Apply Ghost Convolution to input tensor.

        Args:
            x (torch.Tensor): Input tensor.

        Returns:
            (torch.Tensor): Output tensor with concatenated features.
        """
        y = self.cv1(x)
        return torch.cat((y, self.cv2(y)), 1)


class RepConv(nn.Module):
    """RepConv module with training and deploy modes.

    This module is used in RT-DETR and can fuse convolutions during inference for efficiency.

    Attributes:
        conv1 (Conv): 3x3 convolution.
        conv2 (Conv): 1x1 convolution.
        bn (nn.BatchNorm2d, optional): Batch normalization for identity branch.
        act (nn.Module): Activation function.
        default_act (nn.Module): Default activation function (SiLU).

    References:
        https://github.com/DingXiaoH/RepVGG/blob/main/repvgg.py
    """

    default_act = nn.SiLU()  # default activation

    def __init__(self, c1, c2, k=3, s=1, p=1, g=1, d=1, act=True, bn=False, deploy=False):
        """Initialize RepConv module with given parameters.

        Args:
            c1 (int): Number of input channels.
            c2 (int): Number of output channels.
            k (int): Kernel size.
            s (int): Stride.
            p (int): Padding.
            g (int): Groups.
            d (int): Dilation.
            act (bool | nn.Module): Activation function.
            bn (bool): Use batch normalization for identity branch.
            deploy (bool): Deploy mode for inference.
        """
        super().__init__()
        assert k == 3 and p == 1
        self.g = g
        self.c1 = c1
        self.c2 = c2
        self.act = self.default_act if act is True else act if isinstance(act, nn.Module) else nn.Identity()

        self.bn = nn.BatchNorm2d(num_features=c1) if bn and c2 == c1 and s == 1 else None
        self.conv1 = Conv(c1, c2, k, s, p=p, g=g, act=False)
        self.conv2 = Conv(c1, c2, 1, s, p=(p - k // 2), g=g, act=False)

    def forward_fuse(self, x):
        """Forward pass for deploy mode.

        Args:
            x (torch.Tensor): Input tensor.

        Returns:
            (torch.Tensor): Output tensor.
        """
        return self.act(self.conv(x))

    def forward(self, x):
        """Forward pass for training mode.

        Args:
            x (torch.Tensor): Input tensor.

        Returns:
            (torch.Tensor): Output tensor.
        """
        id_out = 0 if self.bn is None else self.bn(x)
        return self.act(self.conv1(x) + self.conv2(x) + id_out)

    def get_equivalent_kernel_bias(self):
        """Calculate equivalent kernel and bias by fusing convolutions.

        Returns:
            (torch.Tensor): Equivalent kernel
            (torch.Tensor): Equivalent bias
        """
        kernel3x3, bias3x3 = self._fuse_bn_tensor(self.conv1)
        kernel1x1, bias1x1 = self._fuse_bn_tensor(self.conv2)
        kernelid, biasid = self._fuse_bn_tensor(self.bn)
        return kernel3x3 + self._pad_1x1_to_3x3_tensor(kernel1x1) + kernelid, bias3x3 + bias1x1 + biasid

    @staticmethod
    def _pad_1x1_to_3x3_tensor(kernel1x1):
        """Pad a 1x1 kernel to 3x3 size.

        Args:
            kernel1x1 (torch.Tensor): 1x1 convolution kernel.

        Returns:
            (torch.Tensor): Padded 3x3 kernel.
        """
        if kernel1x1 is None:
            return 0
        else:
            return torch.nn.functional.pad(kernel1x1, [1, 1, 1, 1])

    def _fuse_bn_tensor(self, branch):
        """Fuse batch normalization with convolution weights.

        Args:
            branch (Conv | nn.BatchNorm2d | None): Branch to fuse.

        Returns:
            kernel (torch.Tensor): Fused kernel.
            bias (torch.Tensor): Fused bias.
        """
        if branch is None:
            return 0, 0
        if isinstance(branch, Conv):
            kernel = branch.conv.weight
            running_mean = branch.bn.running_mean
            running_var = branch.bn.running_var
            gamma = branch.bn.weight
            beta = branch.bn.bias
            eps = branch.bn.eps
        elif isinstance(branch, nn.BatchNorm2d):
            if not hasattr(self, "id_tensor"):
                input_dim = self.c1 // self.g
                kernel_value = np.zeros((self.c1, input_dim, 3, 3), dtype=np.float32)
                for i in range(self.c1):
                    kernel_value[i, i % input_dim, 1, 1] = 1
                self.id_tensor = torch.from_numpy(kernel_value).to(branch.weight.device)
            kernel = self.id_tensor
            running_mean = branch.running_mean
            running_var = branch.running_var
            gamma = branch.weight
            beta = branch.bias
            eps = branch.eps
        std = (running_var + eps).sqrt()
        t = (gamma / std).reshape(-1, 1, 1, 1)
        return kernel * t, beta - running_mean * gamma / std

    def fuse_convs(self):
        """Fuse convolutions for inference by creating a single equivalent convolution."""
        if hasattr(self, "conv"):
            return
        kernel, bias = self.get_equivalent_kernel_bias()
        self.conv = nn.Conv2d(
            in_channels=self.conv1.conv.in_channels,
            out_channels=self.conv1.conv.out_channels,
            kernel_size=self.conv1.conv.kernel_size,
            stride=self.conv1.conv.stride,
            padding=self.conv1.conv.padding,
            dilation=self.conv1.conv.dilation,
            groups=self.conv1.conv.groups,
            bias=True,
        ).requires_grad_(False)
        self.conv.weight.data = kernel
        self.conv.bias.data = bias
        for para in self.parameters():
            para.detach_()
        self.__delattr__("conv1")
        self.__delattr__("conv2")
        if hasattr(self, "nm"):
            self.__delattr__("nm")
        if hasattr(self, "bn"):
            self.__delattr__("bn")
        if hasattr(self, "id_tensor"):
            self.__delattr__("id_tensor")


class ChannelAttention(nn.Module):
    """Channel-attention module for feature recalibration.

    Applies attention weights to channels based on global average pooling.

    Attributes:
        pool (nn.AdaptiveAvgPool2d): Global average pooling.
        fc (nn.Conv2d): Fully connected layer implemented as 1x1 convolution.
        act (nn.Sigmoid): Sigmoid activation for attention weights.

    References:
        https://github.com/open-mmlab/mmdetection/tree/v3.0.0rc1/configs/rtmdet
    """

    def __init__(self, channels: int) -> None:
        """Initialize Channel-attention module.

        Args:
            channels (int): Number of input channels.
        """
        super().__init__()
        self.pool = nn.AdaptiveAvgPool2d(1)
        self.fc = nn.Conv2d(channels, channels, 1, 1, 0, bias=True)
        self.act = nn.Sigmoid()

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        """Apply channel attention to input tensor.

        Args:
            x (torch.Tensor): Input tensor.

        Returns:
            (torch.Tensor): Channel-attended output tensor.
        """
        return x * self.act(self.fc(self.pool(x)))


class SpatialAttention(nn.Module):
    """Spatial-attention module for feature recalibration.

    Applies attention weights to spatial dimensions based on channel statistics.

    Attributes:
        cv1 (nn.Conv2d): Convolution layer for spatial attention.
        act (nn.Sigmoid): Sigmoid activation for attention weights.
    """

    def __init__(self, kernel_size=7):
        """Initialize Spatial-attention module.

        Args:
            kernel_size (int): Size of the convolutional kernel (3 or 7).
        """
        super().__init__()
        assert kernel_size in {3, 7}, "kernel size must be 3 or 7"
        padding = 3 if kernel_size == 7 else 1
        self.cv1 = nn.Conv2d(2, 1, kernel_size, padding=padding, bias=False)
        self.act = nn.Sigmoid()

    def forward(self, x):
        """Apply spatial attention to input tensor.

        Args:
            x (torch.Tensor): Input tensor.

        Returns:
            (torch.Tensor): Spatial-attended output tensor.
        """
        return x * self.act(self.cv1(torch.cat([torch.mean(x, 1, keepdim=True), torch.max(x, 1, keepdim=True)[0]], 1)))


class CBAM(nn.Module):
    """Convolutional Block Attention Module.

    Combines channel and spatial attention mechanisms for comprehensive feature refinement.

    Attributes:
        channel_attention (ChannelAttention): Channel attention module.
        spatial_attention (SpatialAttention): Spatial attention module.
    """

    def __init__(self, c1, kernel_size=7):
        """Initialize CBAM with given parameters.

        Args:
            c1 (int): Number of input channels.
            kernel_size (int): Size of the convolutional kernel for spatial attention.
        """
        super().__init__()
        self.channel_attention = ChannelAttention(c1)
        self.spatial_attention = SpatialAttention(kernel_size)

    def forward(self, x):
        """Apply channel and spatial attention sequentially to input tensor.

        Args:
            x (torch.Tensor): Input tensor.

        Returns:
            (torch.Tensor): Attended output tensor.
        """
        return self.spatial_attention(self.channel_attention(x))


class EMA(nn.Module):
    """Efficient Multi-Scale Attention (EMA) module.

    Based on "Efficient Multi-Scale Attention" (CVPR 2023).
    Applies cross-spatial attention via group-wise horizontal and vertical pooling,
    followed by cross-channel interaction through group normalization and convolutional layers.

    This module is channel-invariant (input channels == output channels) and operates
    as a drop-in feature refinement block after existing convolutional layers.

    Attributes:
        groups (int): Number of groups for group-wise attention.
        softmax (nn.Softmax): Softmax activation for attention weights.
        agp (nn.AdaptiveAvgPool2d): Global average pooling.
        pool_h (nn.AdaptiveAvgPool2d): Horizontal strip pooling.
        pool_w (nn.AdaptiveAvgPool2d): Vertical strip pooling.
        gn (nn.GroupNorm): Group normalization for cross-channel interaction.
        conv1x1 (nn.Conv2d): 1x1 convolution for cross-spatial fusion.
        conv3x3 (nn.Conv2d): 3x3 convolution for local feature enhancement.

    Examples:
        >>> ema = EMA(256, factor=32)
        >>> x = torch.randn(1, 256, 64, 64)
        >>> output = ema(x)
        >>> print(output.shape)
        torch.Size([1, 256, 64, 64])
    """

    def __init__(self, channels: int, factor: int = 32) -> None:
        """Initialize EMA module.

        Args:
            channels (int): Number of input/output channels.
            factor (int): Number of groups for group-wise processing (default: 32).
        """
        super().__init__()
        self.groups = factor
        assert channels // self.groups > 0, f"channels ({channels}) must be > groups ({factor})"
        self.softmax = nn.Softmax(-1)
        self.agp = nn.AdaptiveAvgPool2d((1, 1))
        self.pool_h = nn.AdaptiveAvgPool2d((None, 1))
        self.pool_w = nn.AdaptiveAvgPool2d((1, None))
        self.gn = nn.GroupNorm(channels // self.groups, channels // self.groups)
        self.conv1x1 = nn.Conv2d(channels // self.groups, channels // self.groups, kernel_size=1, stride=1, padding=0)
        self.conv3x3 = nn.Conv2d(channels // self.groups, channels // self.groups, kernel_size=3, stride=1, padding=1)

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        """Apply Efficient Multi-Scale Attention to input tensor.

        Args:
            x (torch.Tensor): Input tensor of shape (B, C, H, W).

        Returns:
            (torch.Tensor): Attended output tensor of same shape.
        """
        b, c, h, w = x.size()
        group_x = x.reshape(b * self.groups, -1, h, w)
        x_h = self.pool_h(group_x)
        x_w = self.pool_w(group_x).permute(0, 1, 3, 2)
        hw = self.conv1x1(torch.cat([x_h, x_w], dim=2))
        x_h, x_w = torch.split(hw, [h, w], dim=2)
        x1 = self.gn(group_x * x_h.sigmoid() * x_w.permute(0, 1, 3, 2).sigmoid())
        x2 = self.conv3x3(group_x)
        x11 = self.softmax(self.agp(x1).reshape(b * self.groups, -1, 1).permute(0, 2, 1))
        x12 = x2.reshape(b * self.groups, c // self.groups, -1)
        x21 = self.softmax(self.agp(x2).reshape(b * self.groups, -1, 1).permute(0, 2, 1))
        x22 = x1.reshape(b * self.groups, c // self.groups, -1)
        weights = (torch.matmul(x11, x12) + torch.matmul(x21, x22)).reshape(b * self.groups, 1, h, w)
        return (group_x * weights.sigmoid()).reshape(b, c, h, w)


class CoordAtt(nn.Module):
    """Coordinate Attention (CA) module.

    Based on "Coordinate Attention for Efficient Mobile Network Design" (CVPR 2021).
    Decomposes channel attention into two 1D feature encoding processes along
    horizontal and vertical directions, capturing long-range spatial dependencies
    with precise positional information.

    This module is channel-invariant (input channels == output channels).

    Attributes:
        pool_h (nn.AdaptiveAvgPool2d): Horizontal strip pooling (None, 1).
        pool_w (nn.AdaptiveAvgPool2d): Vertical strip pooling (1, None).
        conv1 (nn.Conv2d): 1x1 channel reduction convolution.
        bn1 (nn.BatchNorm2d): Batch normalization after channel reduction.
        conv_h (nn.Conv2d): 1x1 convolution for height attention.
        conv_w (nn.Conv2d): 1x1 convolution for width attention.

    Examples:
        >>> ca = CoordAtt(256, reduction=32)
        >>> x = torch.randn(1, 256, 64, 64)
        >>> output = ca(x)
        >>> print(output.shape)
        torch.Size([1, 256, 64, 64])
    """

    def __init__(self, channels: int, reduction: int = 32) -> None:
        """Initialize CoordAtt with coordinate attention parameters.

        Args:
            channels: Number of input/output channels.
            reduction: Channel reduction ratio (default: 32).
        """
        super().__init__()
        self.pool_h = nn.AdaptiveAvgPool2d((None, 1))
        self.pool_w = nn.AdaptiveAvgPool2d((1, None))
        mip = max(8, channels // reduction)
        self.conv1 = nn.Conv2d(channels, mip, kernel_size=1, stride=1, padding=0)
        self.bn1 = nn.BatchNorm2d(mip)
        self.act = nn.ReLU6(inplace=True)
        self.conv_h = nn.Conv2d(mip, channels, kernel_size=1, stride=1, padding=0)
        self.conv_w = nn.Conv2d(mip, channels, kernel_size=1, stride=1, padding=0)

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        """Apply coordinate attention to input tensor.

        Args:
            x: Input tensor of shape (B, C, H, W).

        Returns:
            Attended tensor of shape (B, C, H, W).
        """
        identity = x
        _, _, h, w = x.size()
        x_h = self.pool_h(x)
        x_w = self.pool_w(x).permute(0, 1, 3, 2)
        y = torch.cat([x_h, x_w], dim=2)
        y = self.act(self.bn1(self.conv1(y)))
        x_h, x_w = torch.split(y, [h, w], dim=2)
        x_w = x_w.permute(0, 1, 3, 2)
        a_h = self.conv_h(x_h).sigmoid()
        a_w = self.conv_w(x_w).sigmoid()
        return identity * a_w * a_h


class CoordAttHSwish(nn.Module):
    """Coordinate Attention using the paper's h-swish bottleneck activation.

    This class is intentionally separate from :class:`CoordAtt` so checkpoints
    and results produced by the existing ReLU6 implementation remain
    reproducible. The architecture, placement, reduction ratio, and parameter
    count are otherwise unchanged, isolating the activation-function effect.
    """

    def __init__(self, channels: int, reduction: int = 32) -> None:
        """Initialize h-swish Coordinate Attention."""
        super().__init__()
        self.pool_h = nn.AdaptiveAvgPool2d((None, 1))
        self.pool_w = nn.AdaptiveAvgPool2d((1, None))
        mip = max(8, channels // reduction)
        self.conv1 = nn.Conv2d(channels, mip, kernel_size=1, stride=1, padding=0)
        self.bn1 = nn.BatchNorm2d(mip)
        # nn.Hardswish implements x * ReLU6(x + 3) / 6.
        self.act = nn.Hardswish(inplace=True)
        self.conv_h = nn.Conv2d(mip, channels, kernel_size=1, stride=1, padding=0)
        self.conv_w = nn.Conv2d(mip, channels, kernel_size=1, stride=1, padding=0)

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        """Apply h-swish coordinate attention to an input tensor."""
        identity = x
        _, _, h, w = x.size()
        x_h = self.pool_h(x)
        x_w = self.pool_w(x).permute(0, 1, 3, 2)
        y = torch.cat([x_h, x_w], dim=2)
        y = self.act(self.bn1(self.conv1(y)))
        x_h, x_w = torch.split(y, [h, w], dim=2)
        x_w = x_w.permute(0, 1, 3, 2)
        a_h = self.conv_h(x_h).sigmoid()
        a_w = self.conv_w(x_w).sigmoid()
        return identity * a_w * a_h


class SimAM(nn.Module):
    """SimAM: A Simple, Parameter-Free Attention Module.

    Based on "SimAM: A Simple, Parameter-Free Attention Module for Convolutional
    Neural Networks" (ICML 2021). Infers 3D attention weights (spatial + channel)
    without adding any trainable parameters, based on an energy function derived
    from neuroscience theory (spatial suppression).

    This module is channel-invariant (input channels == output channels).

    Attributes:
        lambd (float): Regularization coefficient for energy computation.

    Examples:
        >>> simam = SimAM()
        >>> x = torch.randn(1, 256, 64, 64)
        >>> output = simam(x)
        >>> print(output.shape)
        torch.Size([1, 256, 64, 64])
    """

    def __init__(self, lambd: float = 1e-4) -> None:
        """Initialize SimAM with regularization coefficient.

        Args:
            lambd: Lambda coefficient for energy function (default: 1e-4).
        """
        super().__init__()
        self.lambd = lambd

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        """Apply SimAM attention to input tensor.

        Args:
            x: Input tensor of shape (B, C, H, W).

        Returns:
            Attended tensor of shape (B, C, H, W), multiplied by sigmoid attention.
        """
        # Spatial size minus 1
        n = x.shape[2] * x.shape[3] - 1
        # Mean over spatial dimensions
        mu = x.mean(dim=(2, 3), keepdim=True)
        # (x - mu)^2
        d = (x - mu).pow(2)
        # Variance over spatial dimensions
        v = d.sum(dim=(2, 3), keepdim=True) / n
        # Energy inverse E_inv
        e_inv = d / (4 * (v + self.lambd)) + 0.5
        return x * e_inv.sigmoid()


class _TripletZPool(nn.Module):
    """Compress a feature tensor to channel-wise max and mean maps."""

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        return torch.cat((torch.max(x, 1, keepdim=True)[0], torch.mean(x, 1, keepdim=True)), dim=1)


class _TripletAttentionGate(nn.Module):
    """Generate one spatial gate for a Triplet Attention branch."""

    def __init__(self, kernel_size: int = 7) -> None:
        super().__init__()
        self.compress = _TripletZPool()
        self.spatial = nn.Sequential(
            nn.Conv2d(2, 1, kernel_size, stride=1, padding=kernel_size // 2, bias=False),
            nn.BatchNorm2d(1),
        )

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        return x * self.spatial(self.compress(x)).sigmoid()


class TripletAttention(nn.Module):
    """Cross-dimensional Triplet Attention from WACV 2021.

    The rotated branches model channel-height and channel-width interactions;
    the third branch models ordinary spatial attention. Their outputs preserve
    the input shape, so the module is a controlled drop-in replacement for CA.
    """

    def __init__(self, kernel_size: int = 7, no_spatial: bool = False) -> None:
        super().__init__()
        self.cw = _TripletAttentionGate(kernel_size)
        self.hc = _TripletAttentionGate(kernel_size)
        self.no_spatial = no_spatial
        if not no_spatial:
            self.hw = _TripletAttentionGate(kernel_size)

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        x_out1 = self.cw(x.permute(0, 2, 1, 3).contiguous()).permute(0, 2, 1, 3).contiguous()
        x_out2 = self.hc(x.permute(0, 3, 2, 1).contiguous()).permute(0, 3, 2, 1).contiguous()
        if self.no_spatial:
            return 0.5 * (x_out1 + x_out2)
        return (x_out1 + x_out2 + self.hw(x)) / 3.0


class LSKA(nn.Module):
    """Large Separable Kernel Attention from Lau et al. (2024).

    A large depthwise 2-D kernel is factorized into cascaded horizontal and
    vertical 1-D kernels. The paper's multiplicative attention form is retained.
    """

    _KERNELS = {
        7: (3, 3, 2),
        11: (3, 5, 2),
        23: (5, 7, 3),
        35: (5, 11, 3),
        41: (5, 13, 3),
        53: (7, 17, 3),
    }

    def __init__(self, channels: int, kernel_size: int = 11) -> None:
        super().__init__()
        if kernel_size not in self._KERNELS:
            raise ValueError(f"Unsupported LSKA kernel_size={kernel_size}; choose {tuple(self._KERNELS)}")
        local_k, dilated_k, dilation = self._KERNELS[kernel_size]
        local_pad = local_k // 2
        dilated_pad = dilation * (dilated_k // 2)
        self.conv0h = nn.Conv2d(channels, channels, (1, local_k), padding=(0, local_pad), groups=channels)
        self.conv0v = nn.Conv2d(channels, channels, (local_k, 1), padding=(local_pad, 0), groups=channels)
        self.conv_spatial_h = nn.Conv2d(
            channels, channels, (1, dilated_k), padding=(0, dilated_pad), dilation=(1, dilation), groups=channels
        )
        self.conv_spatial_v = nn.Conv2d(
            channels, channels, (dilated_k, 1), padding=(dilated_pad, 0), dilation=(dilation, 1), groups=channels
        )
        self.conv1 = nn.Conv2d(channels, channels, 1)

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        attention = self.conv0v(self.conv0h(x))
        attention = self.conv_spatial_v(self.conv_spatial_h(attention))
        return x * self.conv1(attention)


class Concat(nn.Module):
    """Concatenate a list of tensors along specified dimension.

    Attributes:
        d (int): Dimension along which to concatenate tensors.
    """

    def __init__(self, dimension=1):
        """Initialize Concat module.

        Args:
            dimension (int): Dimension along which to concatenate tensors.
        """
        super().__init__()
        self.d = dimension

    def forward(self, x: list[torch.Tensor]):
        """Concatenate input tensors along specified dimension.

        Args:
            x (list[torch.Tensor]): List of input tensors.

        Returns:
            (torch.Tensor): Concatenated tensor.
        """
        return torch.cat(x, self.d)


class Index(nn.Module):
    """Returns a particular index of the input.

    Attributes:
        index (int): Index to select from input.
    """

    def __init__(self, index=0):
        """Initialize Index module.

        Args:
            index (int): Index to select from input.
        """
        super().__init__()
        self.index = index

    def forward(self, x: list[torch.Tensor]):
        """Select and return a particular index from input.

        Args:
            x (list[torch.Tensor]): List of input tensors.

        Returns:
            (torch.Tensor): Selected tensor.
        """
        return x[self.index]
