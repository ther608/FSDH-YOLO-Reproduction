#!/usr/bin/env python
"""Train and evaluate FSDH-YOLO on Dataset A or B under the paper protocol.

This is a convenience wrapper around the archived scripts:

  train/origin_train.py
  train/val.py
  eval/eval_ultralytics_common_evaluator.py
  eval/benchmark_uniform_latency.py

It does not modify the archived scripts. Use --plan-only to print every
command without starting a run.

Examples
--------
Dataset A (3 seeds, both models, train -> val -> Common Evaluator):
  python train/run_reproduction.py --dataset a \
      --dataset-root /path/to/lychee_groupaware_clean_aug_v2

Dataset B:
  python train/run_reproduction.py --dataset b \
      --dataset-root /path/to/lichi_701515_groupaware_clean_v4_aug

Only evaluate existing checkpoints (no training):
  python train/run_reproduction.py --dataset a --dataset-root ... --skip-train
"""

from __future__ import annotations

import argparse
import csv
import os
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
PYTHON = sys.executable


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--dataset", choices=("a", "b"), required=True)
    parser.add_argument(
        "--dataset-root",
        type=Path,
        required=True,
        help="Root of the augmented dataset (the directory that contains images/ or train/).",
    )
    parser.add_argument(
        "--data-yaml",
        type=Path,
        default=None,
        help="Use an existing dataset YAML; otherwise a runtime YAML is written under runs/_data/.",
    )
    parser.add_argument("--seeds", type=int, nargs="+", default=[0, 1, 2])
    parser.add_argument("--models", nargs="+", choices=("YOLO11n", "FSDH-YOLO"), default=["YOLO11n", "FSDH-YOLO"])
    parser.add_argument("--epochs", type=int, default=300)
    parser.add_argument("--batch", type=int, default=12)
    parser.add_argument("--test-batch", type=int, default=16)
    parser.add_argument("--workers", type=int, default=6)
    parser.add_argument("--val-workers", type=int, default=2)
    parser.add_argument("--patience", type=int, default=100)
    parser.add_argument("--device", default="0")
    parser.add_argument("--project", type=Path, default=None, help="Output root (default: runs/<dataset>).")
    parser.add_argument("--annotations", type=Path, default=None, help="Override the frozen test COCO annotations.")
    parser.add_argument("--latency", action="store_true", help="Also run the FP32 batch-1 latency benchmark.")
    parser.add_argument("--latency-image", type=Path, default=None)
    parser.add_argument("--overwrite", action="store_true", help="Retrain even if best.pt already exists.")
    parser.add_argument("--skip-train", action="store_true")
    parser.add_argument("--skip-val", action="store_true")
    parser.add_argument("--skip-common", action="store_true")
    parser.add_argument("--plan-only", action="store_true")
    return parser.parse_args()


def write_runtime_yaml(dataset: str, root: Path, out: Path) -> Path:
    out.parent.mkdir(parents=True, exist_ok=True)
    if dataset == "a":
        body = f"""# Runtime YAML generated by train/run_reproduction.py
path: {root.as_posix()}
train: images/train
val: images/val
test: images/test
nc: 3
names:
  0: unripe
  1: semi-ripe
  2: ripe
"""
    else:
        body = f"""# Runtime YAML generated by train/run_reproduction.py
path: {root.as_posix()}
train: train/images
val: val/images
test: test/images
nc: 4
names:
  0: green
  1: half
  2: red
  3: young
"""
    out.write_text(body, encoding="utf-8")
    return out


def resolve_test_images(data_yaml: Path) -> Path:
    try:
        import yaml
    except ImportError as exc:  # pragma: no cover
        raise SystemExit("PyYAML is required to resolve the test split from --data-yaml") from exc
    data = yaml.safe_load(data_yaml.read_text(encoding="utf-8"))
    root = Path(data.get("path", data_yaml.parent))
    if not root.is_absolute():
        root = (data_yaml.parent / root).resolve()
    value = data["test"]
    if isinstance(value, list):
        value = value[0]
    path = Path(value)
    return path if path.is_absolute() else (root / path).resolve()


def first_image(directory: Path) -> Path:
    suffixes = {".jpg", ".jpeg", ".png", ".bmp", ".tif", ".tiff", ".webp"}
    images = sorted(p for p in directory.rglob("*") if p.suffix.lower() in suffixes)
    if not images:
        raise SystemExit(f"No test image found under {directory}")
    return images[0]


def run(cmd: list[str], env: dict[str, str], plan_only: bool) -> None:
    printable = " ".join(f'"{c}"' if " " in c else c for c in cmd)
    print("> " + printable, flush=True)
    if plan_only:
        return
    subprocess.run(cmd, check=True, env=env)


def main() -> None:
    args = parse_args()
    root = args.dataset_root.resolve()
    if not root.is_dir():
        raise SystemExit(f"Dataset root not found: {root}")

    project = (args.project or (REPO / "runs" / args.dataset)).resolve()
    project.mkdir(parents=True, exist_ok=True)

    if args.data_yaml:
        data_yaml = args.data_yaml.resolve()
    else:
        data_yaml = write_runtime_yaml(args.dataset, root, project / "_data" / f"dataset_{args.dataset}.yaml")
    test_images = resolve_test_images(data_yaml)
    if not test_images.is_dir():
        raise SystemExit(f"Test image directory not found: {test_images}")

    if args.annotations:
        annotations = args.annotations.resolve()
    else:
        annotations = REPO / "annotations" / f"dataset_{args.dataset}_test_instances.json"
    if not annotations.is_file():
        raise SystemExit(f"Annotation file not found: {annotations}")

    pretrained = REPO / "weights" / "pretrained" / "yolo11n.pt"
    fsdh_config = REPO / "configs" / "yolo11n_FSDConv-SHAB.yaml"
    if not pretrained.is_file() or not fsdh_config.is_file():
        raise SystemExit("Missing bundled pretrained weights or FSDH-YOLO config")

    specs = {
        "YOLO11n": {
            "label": "YOLO11n",
            "run_base": {
                "a": "dsA_groupaware_clean_aug_v2__scale__yolo11n",
                "b": "dsB_groupaware_clean_v4_aug__comparison__yolo11n",
            }[args.dataset],
            "model": str(pretrained),
            "init": [],
        },
        "FSDH-YOLO": {
            "label": "FSDH-YOLO" if args.dataset == "a" else "FSDH-YOLO-n",
            "run_base": {
                "a": "dsA_groupaware_clean_aug_v2__fsd_completion__fsd_shab",
                "b": "dsB_groupaware_clean_v4_aug__comparison__fsdh_yolo_n",
            }[args.dataset],
            "model": str(fsdh_config),
            "init": ["--weights", str(pretrained), "--weights-map", "none"],
        },
    }

    env = os.environ.copy()
    env["PYTHONPATH"] = str(REPO / "src") + os.pathsep + env.get("PYTHONPATH", "")
    train_root = project / "train"
    test_root = project / "test"
    common_root = project / "common_eval"
    latency_root = project / "latency"
    for directory in (train_root, test_root, common_root, latency_root):
        directory.mkdir(parents=True, exist_ok=True)

    print(f"Repo        : {REPO}")
    print(f"Dataset     : {args.dataset.upper()}  root={root}")
    print(f"Data YAML   : {data_yaml}")
    print(f"Test images : {test_images}")
    print(f"Annotations : {annotations}")
    print(f"Project     : {project}")
    print(f"Models      : {', '.join(args.models)}")
    print(f"Seeds       : {args.seeds}")
    print(f"Python      : {PYTHON}")
    print()

    for model_name in args.models:
        spec = specs[model_name]
        for seed in args.seeds:
            run_name = f"{spec['run_base']}__seed{seed}"
            best = train_root / run_name / "weights" / "best.pt"

            if not args.skip_train:
                if best.exists() and not args.overwrite:
                    print(f"[skip train] {best} exists (use --overwrite to retrain)")
                else:
                    if (train_root / run_name).exists() and not args.overwrite:
                        raise SystemExit(
                            f"Run directory already exists without a usable best.pt: {train_root / run_name}. "
                            "Remove it or pass --overwrite."
                        )
                    cmd = [
                        PYTHON,
                        str(REPO / "train" / "origin_train.py"),
                        "--model",
                        spec["model"],
                        "--data",
                        str(data_yaml),
                        "--project",
                        str(train_root),
                        "--name",
                        run_name,
                        "--epochs",
                        str(args.epochs),
                        "--batch",
                        str(args.batch),
                        "--imgsz",
                        "640",
                        "--workers",
                        str(args.workers),
                        "--val-workers",
                        str(args.val_workers),
                        "--patience",
                        str(args.patience),
                        "--seed",
                        str(seed),
                        "--fraction",
                        "1.0",
                        "--iou-type",
                        "ciou",
                    ] + spec["init"]
                    run(cmd, env, args.plan_only)

            if not args.skip_val:
                cmd = [
                    PYTHON,
                    str(REPO / "train" / "val.py"),
                    "--model",
                    str(best),
                    "--data",
                    str(data_yaml),
                    "--project",
                    str(test_root),
                    "--name",
                    f"{run_name}_test",
                    "--batch",
                    str(args.test_batch),
                    "--imgsz",
                    "640",
                ]
                run(cmd, env, args.plan_only)

            if not args.skip_common:
                common_dir = common_root / spec["label"]
                common_dir.mkdir(parents=True, exist_ok=True)
                cmd = [
                    PYTHON,
                    str(REPO / "eval" / "eval_ultralytics_common_evaluator.py"),
                    "--model",
                    str(best),
                    "--model-name",
                    spec["label"],
                    "--seed",
                    str(seed),
                    "--images",
                    str(test_images),
                    "--annotations",
                    str(annotations),
                    "--out",
                    str(common_dir / f"seed{seed}__test_metrics_common.json"),
                    "--predictions-out",
                    str(common_dir / f"seed{seed}__test_predictions_coco.json"),
                    "--imgsz",
                    "640",
                    "--device",
                    args.device,
                    "--conf",
                    "0.001",
                    "--iou",
                    "0.7",
                    "--max-det",
                    "300",
                    "--bins",
                    "15",
                    "--area-scale",
                    "4" if args.dataset == "a" else "1",
                ]
                run(cmd, env, args.plan_only)

            if args.latency:
                latency_dir = latency_root / run_name
                latency_dir.mkdir(parents=True, exist_ok=True)
                manifest = latency_dir / "latency_manifest.csv"
                if not args.plan_only:
                    with manifest.open("w", newline="", encoding="utf-8-sig") as handle:
                        writer = csv.DictWriter(handle, fieldnames=["section", "model", "seed", "weights", "imgsz"])
                        writer.writeheader()
                        writer.writerow(
                            {
                                "section": args.dataset,
                                "model": spec["label"],
                                "seed": seed,
                                "weights": str(best),
                                "imgsz": 640,
                            }
                        )
                image = args.latency_image.resolve() if args.latency_image else first_image(test_images)
                cmd = [
                    PYTHON,
                    str(REPO / "eval" / "benchmark_uniform_latency.py"),
                    "--manifest",
                    str(manifest),
                    "--image",
                    str(image),
                    "--out",
                    str(latency_dir),
                    "--imgsz",
                    "640",
                    "--warmup",
                    "100",
                    "--iterations",
                    "500",
                ]
                run(cmd, env, args.plan_only)

    print()
    print("Done." if not args.plan_only else "Plan only; no command was executed.")


if __name__ == "__main__":
    main()
